export type AppLanguage = (typeof appLanguages)[number]["code"];

export const defaultLanguage: AppLanguage = "ko";
export const localeStorageKey = "doul.locale";

const languageCodes = new Set<AppLanguage>(
  appLanguages.map((language) => language.code),
);

export function normalizeLanguage(value?: string | null): AppLanguage {
  if (!value) return defaultLanguage;
  const base = value.toLowerCase().split("-")[0] as AppLanguage;
  return languageCodes.has(base) ? base : defaultLanguage;
}

export function intlLocaleFor(value?: string | null): string {
  const language = normalizeLanguage(value);
  return (
    appLanguages.find((candidate) => candidate.code === language)?.tag ??
    "ko-KR"
  );
}

export function languageDirection(value?: string | null): "ltr" | "rtl" {
  const language = normalizeLanguage(value);
  return (
    appLanguages.find((candidate) => candidate.code === language)?.direction ??
    "ltr"
  );
}

