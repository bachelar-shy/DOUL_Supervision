import { expect, test, type Page, type Route } from "@playwright/test";
import { spawn, type ChildProcess } from "node:child_process";
import { randomBytes, randomUUID } from "node:crypto";
import { mkdirSync, rmSync } from "node:fs";
import { createServer } from "node:net";
import { delimiter, join, resolve } from "node:path";
import type { Workspace } from "../apps/web/src/data/ui-contract";
import { eligibleDocumentSources } from "../apps/web/src/pages/document-authoring-source";

let apiOrigin = "";
let fixtureProcess: ChildProcess | undefined;
let fixtureDatabase = "";
let fixtureStderr = "";

if (process.env.DOUL_TEST_CHROMIUM) {
  test.use({ launchOptions: { executablePath: process.env.DOUL_TEST_CHROMIUM, args: ["--no-sandbox"] } });
}

test.beforeAll(async () => {
  const server = createServer();
  await new Promise<void>(resolveListen => server.listen(0, "127.0.0.1", resolveListen));
  const address = server.address();
  if (!address || typeof address === "string") throw new Error("Missing fixture port");
  const port = address.port;
  await new Promise<void>((resolveClose, reject) => server.close(error => error ? reject(error) : resolveClose()));
  apiOrigin = `http://127.0.0.1:${port}`;
  mkdirSync(join(process.cwd(), "work"), { recursive: true });
  fixtureDatabase = join(process.cwd(), "work", `pr178-documents-${randomUUID()}.sqlite3`);
  // Reuse a trusted prerequisite fixture. It seeds a readable MethodStatement;
  // document snapshots are still generated by the actual product API.
  fixtureProcess = spawn(process.env.DOUL_TEST_PYTHON || resolve(".venv/bin/python"), [
    resolve("tests_browser/support/safety_equipment_api_fixture.py"),
    "--database", fixtureDatabase, "--port", String(port),
  ], {
    cwd: process.cwd(),
    env: {
      ...process.env,
      SAFETY_EQUIPMENT_TEST_FIXTURE_TOKEN: randomBytes(32).toString("hex"),
      PYTHONPATH: [process.cwd(), process.env.PYTHONPATH].filter(Boolean).join(delimiter),
    },
    stdio: ["ignore", "ignore", "pipe"],
  });
  fixtureProcess.stderr?.on("data", chunk => { fixtureStderr += String(chunk); });
  await expect.poll(async () => {
    if (fixtureProcess?.exitCode !== null) throw new Error(fixtureStderr);
    try { return (await fetch(`${apiOrigin}/health`)).status; }
    catch { return 0; }
  }, { timeout: 30000 }).toBe(200);
});

test.afterAll(async () => {
  if (fixtureProcess && fixtureProcess.exitCode === null) {
    const child = fixtureProcess;
    child.kill("SIGTERM");
    await new Promise<void>(resolveExit => {
      const timeout = setTimeout(() => { child.kill("SIGKILL"); resolveExit(); }, 3000);
      child.once("exit", () => { clearTimeout(timeout); resolveExit(); });
    });
  }
  for (const path of [fixtureDatabase, `${fixtureDatabase}-wal`, `${fixtureDatabase}-shm`]) {
    if (fixtureDatabase) rmSync(path, { force: true });
  }
});

function forward(route: Route) {
  const url = new URL(route.request().url());
  return route.fetch({
    url: `${apiOrigin}${url.pathname.replace(/^\/api/, "")}${url.search}`,
    headers: { ...route.request().headers(), Origin: "http://127.0.0.1:5181" },
  });
}

test.beforeEach(async ({ page }) => {
  await page.route("**/api/**", async route => {
    await route.fulfill({ response: await forward(route) });
  });
});

async function openEditor(page: Page): Promise<Workspace> {
  const workspaceResponse = page.waitForResponse(response => response.url().endsWith("/workspace"));
  await page.goto("/#/documents");
  await expect(page.getByLabel("문서 양식")).toBeVisible();
  return (await workspaceResponse).json();
}

async function prepareFinal(page: Page) {
  await page.getByLabel("문서 양식").selectOption("FM-20");
  const source = page.getByLabel("문서 원본 선택");
  const options = await source.locator("option").evaluateAll(nodes =>
    nodes.map(node => (node as HTMLOptionElement).value).filter(Boolean));
  expect(options.length).toBeGreaterThan(0);
  await source.selectOption(options[0]);
  await page.getByLabel("렌더링 종류").selectOption("final");
  for (const input of await page.locator(".document-fields input").all()) {
    const type = await input.getAttribute("type");
    await input.fill(type === "datetime-local" ? "2026-10-11T10:00" : "검토한 제출 내용");
  }
}

async function holdFinal(page: Page) {
  let release!: () => void;
  let captured!: () => void;
  const gate = new Promise<void>(resolveGate => { release = resolveGate; });
  const ready = new Promise<void>(resolveReady => { captured = resolveReady; });
  await page.route(/\/forms\/FM-20\/render$/, async route => {
    const response = await forward(route);
    expect(response.status(), await response.text()).toBe(200);
    captured();
    await gate;
    await route.fulfill({ response });
  });
  await page.getByRole("button", { name: "최종 HTML 확인 당시 기록 생성", exact: true }).click();
  await ready;
  return async () => {
    const response = page.waitForResponse(result => result.url().endsWith("/forms/FM-20/render"));
    release();
    await response;
    await page.waitForLoadState("networkidle");
  };
}

test("a delayed final preserves subsequent input and invalidates the old preview/export", async ({ page }) => {
  await openEditor(page);
  await prepareFinal(page);
  const finish = await holdFinal(page);
  await page.locator('input[name="urgent.next_action"]').fill("응답 대기 중 새로 작성한 후속 조치");
  await finish();
  await expect(page.locator('input[name="urgent.next_action"]')).toHaveValue("응답 대기 중 새로 작성한 후속 조치");
  await expect(page.getByRole("button", { name: "PDF 다운로드", exact: true })).toBeDisabled();
  await expect(page.locator(".preview-pane iframe")).toHaveCount(0);
  await page.reload();
  await expect(page.locator('input[name="urgent.next_action"]')).toHaveValue("응답 대기 중 새로 작성한 후속 조치");
});

test("an unchanged successful final clears the submitted draft and keeps its exact preview", async ({ page }) => {
  await openEditor(page);
  await prepareFinal(page);
  const responsePromise = page.waitForResponse(response => response.url().endsWith("/forms/FM-20/render"));
  await page.getByRole("button", { name: "최종 HTML 확인 당시 기록 생성", exact: true }).click();
  const response = await responsePromise;
  expect(response.status(), await response.text()).toBe(200);
  const snapshot = await response.json();
  expect(snapshot.status).toBe("final");
  await expect(page.locator(".preview-pane iframe")).toHaveCount(1);
  await expect(page.locator(".snapshot-note")).toContainText(snapshot.id.slice(0, 8));
  await expect(page.getByLabel("렌더링 종류")).toHaveValue("draft");
  await expect(page.locator('input[name="urgent.next_action"]')).toHaveValue("");
  await expect(page.getByRole("button", { name: "PDF 다운로드", exact: true })).toBeEnabled();
  await page.reload();
  await expect(page.locator('input[name="urgent.next_action"]')).toHaveValue("");
});

test("an unmounted final cannot clear the replacement editor's draft at the same storage key", async ({ page }) => {
  await openEditor(page);
  await prepareFinal(page);
  const finish = await holdFinal(page);
  await page.evaluate(() => { location.hash = "#/today"; });
  await expect(page.getByLabel("문서 양식")).toHaveCount(0);
  await page.evaluate(() => { location.hash = "#/documents"; });
  await expect(page.getByLabel("문서 양식")).toBeVisible();
  await page.getByLabel("문서 양식").selectOption("FM-21");
  await page.locator('input[name="decision.issue"]').fill("다시 연 편집기에서 작성한 결정 요청");
  await finish();
  await page.reload();
  await expect(page.getByLabel("문서 양식")).toHaveValue("FM-21");
  await expect(page.locator('input[name="decision.issue"]')).toHaveValue("다시 연 편집기에서 작성한 결정 요청");
  await expect(page.locator(".preview-pane iframe")).toHaveCount(0);
});

test("a delayed prior-role final cannot clear either role's pending draft", async ({ page }) => {
  const originalWorkspace = await openEditor(page);
  await prepareFinal(page);
  const finish = await holdFinal(page);
  const ownerWorkspace = page.waitForResponse(response => response.url().endsWith("/workspace"));
  await page.getByLabel("시험 사용자 역할 선택").selectOption("OWN");
  await ownerWorkspace;
  await page.evaluate(() => { location.hash = "#/documents"; });
  await expect(page.getByLabel("문서 양식")).toBeVisible();
  await page.getByLabel("문서 양식").selectOption("FM-21");
  await page.locator('input[name="decision.issue"]').fill("발주처가 작성 중인 결정 요청");
  await finish();
  await expect(page.locator('input[name="decision.issue"]')).toHaveValue("발주처가 작성 중인 결정 요청");
  const supervisorWorkspace = page.waitForResponse(response => response.url().endsWith("/workspace"));
  await page.getByLabel("시험 사용자 역할 선택").selectOption("SUP");
  await supervisorWorkspace;
  await page.evaluate(() => { location.hash = "#/documents"; });
  await expect(page.getByLabel("문서 양식")).toHaveValue("FM-20");
  await expect(page.locator('input[name="urgent.next_action"]')).toHaveValue("검토한 제출 내용");
  expect(originalWorkspace.role.actorGroup).toBe("SUP");
});

test("FM-02 renders an actual readable MethodStatement at its exact catalog version", async ({ page }) => {
  const workspace = await openEditor(page);
  const method = workspace.context.referenceCatalog?.informationItems.find(source => source.record.subtype === "MethodStatement");
  expect(method).toBeDefined();
  if (!method) throw new Error("Readable MethodStatement fixture missing");
  expect(workspace.items.some(item => item.record.id === method.record.id)).toBe(false);
  await page.getByLabel("문서 양식").selectOption("FM-02");
  await expect(page.getByLabel("문서 원본 선택").locator(`option[value="${method.ref.objectId}"]`)).toHaveCount(1);
  await page.getByLabel("문서 원본 선택").selectOption(method.ref.objectId);
  await page.locator('input[name="review.conclusion"]').fill("검토 의견 보존");
  await page.getByRole("textbox", { name: "review.design", exact: true }).fill("구조 상세 도면 검토 완료");
  const responsePromise = page.waitForResponse(response => response.url().endsWith("/forms/FM-02/preview"));
  await page.getByRole("button", { name: "초안 미리보기 생성", exact: true }).click();
  const response = await responsePromise;
  expect(response.status(), await response.text()).toBe(200);
  expect(response.request().postDataJSON().sourceDomainRefs).toEqual([method.ref]);
  const snapshot = await response.json();
  expect(snapshot.status).toBe("draft");
  expect(snapshot.sourcePayload.sources).toEqual([{ ref: method.ref, record: method.record }]);
  expect(snapshot.sourcePayload.data.review).toMatchObject({
    conclusion: "검토 의견 보존", design: "구조 상세 도면 검토 완료",
  });
  await expect(page.locator(".preview-pane iframe")).toHaveCount(1);
  // Any new editor input invalidates the previous snapshot and its downloads.
  await expect(page.getByRole("button", { name: "PDF 다운로드", exact: true })).toBeEnabled();
  await page.locator('input[name="review.conclusion"]').fill("새 검토 의견");
  await expect(page.getByRole("button", { name: "PDF 다운로드", exact: true })).toBeDisabled();
  await expect(page.locator(".preview-pane iframe")).toHaveCount(0);

  const unsafeCatalog = structuredClone(workspace);
  const entries = unsafeCatalog.context.referenceCatalog!.informationItems;
  entries.push({ ...method, ref: { ...method.ref, objectType: "WorkItem" } });
  entries.push({ ...method, record: { ...method.record, projectId: "another-project" } });
  entries.push({ ...method, ref: { ...method.ref, version: method.ref.version + 1 } });
  expect(eligibleDocumentSources(unsafeCatalog, "FM-02")).toEqual([method]);
});
