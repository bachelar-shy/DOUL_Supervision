import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
test('inspection author selects exact drawing, location, requirement and evidence without automatic prechecks', async ({page}) => {
  await page.goto('/#/inspections');
  await expect(page.locator('[data-ui-component="workspace-main"]')).toBeVisible({timeout:30000});
  await page.getByLabel('시험 사용자 역할 선택').selectOption('CON');
  await page.goto('/#/inspections');
  // The form opens from the contractor's explicit creation action, rather
  // than occupying the inspection list before the user requests it.
  await expect(page.locator('[data-ui-component="new-inspection-entry"]')).toBeVisible();
  await page.getByRole('button', { name: '＋ 신규 검측', exact: true }).click();
  const form = page.getByRole('form', {name:'자체검측 작성'});
  await expect(form).toBeVisible({timeout:30000});
  const drawingSelect = form.getByLabel('검측 기준 도면');
  await expect(drawingSelect).toBeEnabled();
  const drawings = await drawingSelect.locator('option').evaluateAll(nodes => nodes.map(node => ({value:(node as HTMLOptionElement).value,label:node.textContent})));
  expect(drawings.length).toBeGreaterThan(1);
  await drawingSelect.selectOption(drawings[1].value);
  const locationSelect = form.getByLabel('검측 위치');
  await expect(locationSelect).toBeEnabled();
  const location = await locationSelect.locator('option').nth(1).getAttribute('value');
  await locationSelect.selectOption(location!);
  const requirements = form.getByRole('group',{name:'검측 기준',exact:true});
  const evidence = form.getByRole('group',{name:'현장 증빙',exact:true});
  await expect(requirements.getByRole('checkbox').first()).toBeEnabled();
  await requirements.getByRole('checkbox').first().check();
  await evidence.getByRole('checkbox').first().check();
  await expect(form.getByLabel('자체검측 완료',{exact:true})).not.toBeChecked();
  await expect(form.getByLabel('도면 확인',{exact:true})).not.toBeChecked();
  const workName = `Browser selected inspection ${randomUUID().slice(0,8)}`;
  await form.getByLabel('공종·작업명').fill(workName);
  const saved = page.waitForResponse(response => response.url().endsWith('/inspection-authoring/drafts') && response.request().method()==='POST');
  await form.getByRole('button',{name:'자체검측 초안 저장',exact:true}).click();
  const response = await saved; expect(response.status(),await response.text()).toBe(201);
  const {record} = await response.json();
  expect(record.workName).toBe(workName); expect(record.drawingRef.objectId).toBe(drawings[1].value); expect(record.locationId).toBe(location);
  expect(record.requirementRefs).toHaveLength(1); expect(record.evidenceIds).toHaveLength(1);
  expect(record.status).toBe('draft'); expect(record.selfInspectionComplete).toBe(false); expect(Object.values(record.precheck).some(Boolean)).toBe(false); expect(record.nextWorkAllowed).toBe(false);
  await expect(page.getByRole('heading',{name:workName,exact:true})).toBeVisible();
});
