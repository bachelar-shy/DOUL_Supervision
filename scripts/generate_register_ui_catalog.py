"""Generate the web register UI catalog from authoritative register contracts."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG_PATH = ROOT / "app/schema/register_catalog.json"
PROJECTION_PATH = ROOT / "app/schema/register_projection_map_v2.json"
OUTPUT_PATH = ROOT / "apps/web/src/data/register-projection-catalog.generated.ts"


def generate() -> str:
    catalog = json.loads(CATALOG_PATH.read_text())
    projection_map = json.loads(PROJECTION_PATH.read_text())
    names = {item["id"]: item["name"] for item in catalog["registers"]}
    parts = [
        "// Generated by scripts/generate_register_ui_catalog.py.",
        "// app/schema/register_catalog.json and register_projection_map_v2.json remain authoritative.",
        "",
        "export interface RegisterProjectionSource {",
        "  objectType: string;",
        "  subtype: string | null;",
        "}",
        "",
        "export interface RegisterProjectionDefinition {",
        "  id: string;",
        "  name: string;",
        "  sources: readonly RegisterProjectionSource[];",
        "  calculatedFields: readonly string[];",
        "  mode: string;",
        "  statusSource: string;",
        "  rawStatusPatch: boolean;",
        "}",
        "",
        "export const registerProjectionCatalog = [",
    ]
    for item in projection_map["registers"]:
        rid = item["register_id"]
        parts.extend(
            [
                "  {",
                f"    id: {json.dumps(rid, ensure_ascii=False)},",
                f"    name: {json.dumps(names[rid], ensure_ascii=False)},",
                "    sources: [",
            ]
        )
        for source in item["sources"]:
            parts.append(
                "      { objectType: "
                + json.dumps(source["object_type"], ensure_ascii=False)
                + ", subtype: "
                + json.dumps(source.get("subtype"), ensure_ascii=False)
                + " },"
            )
        parts.extend(
            [
                "    ],",
                "    calculatedFields: "
                + json.dumps(item.get("calculated_fields", []), ensure_ascii=False)
                + ",",
                f"    mode: {json.dumps(item.get('mode', 'read_only'), ensure_ascii=False)},",
                f"    statusSource: {json.dumps(item.get('status_source', ''), ensure_ascii=False)},",
                "    rawStatusPatch: "
                + ("true" if item.get("raw_status_patch") else "false")
                + ",",
                "  },",
            ]
        )
    parts.extend(
        [
            "] as const satisfies readonly RegisterProjectionDefinition[];",
            "",
            'export type RegisterId = (typeof registerProjectionCatalog)[number]["id"];',
            "",
        ]
    )
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not OUTPUT_PATH.exists() or OUTPUT_PATH.read_text() != output:
            raise SystemExit(
                "Web register catalog is stale: run python3 scripts/generate_register_ui_catalog.py"
            )
        print("Web register catalog is current")
        return
    OUTPUT_PATH.write_text(output)
    print("Generated web register catalog")


if __name__ == "__main__":
    main()
