"""Generate presentation input types from Product's Schedule schemas."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = json.loads((ROOT / 'app/schema/domain_schemas_v2.json').read_text())['components']['schemas']
CONTRACT = json.loads((ROOT / 'app/schema/schedule_execution_contract_v1.json').read_text())
SOURCE_IMPORT = json.loads((ROOT / 'app/schema/schedule_source_import_contract_v1.json').read_text())
BLOCKED = set(CONTRACT['server_managed_timestamps']) | {
    'importedAt', 'supersedesRef', 'variance', 'approvalRef', 'ownerDecisionRef',
    'actualsVerified', 'forecastVerified', 'criticalPathReviewed', 'varianceExplained', 'effectivenessResult',
}
NAMES = {'schedule_baseline': 'ScheduleData', 'schedule_progress': 'ScheduleData',
         'delay_event': 'DelayEventData', 'recovery_plan': 'RecoveryPlanData'}


def render():
    configs = {}
    for machine, name in NAMES.items():
        schema = SCHEMAS[name]
        configs[machine] = {
            'required': schema['required'],
            'fields': {key: {'type': value.get('type', 'object'), **({'enum': value['enum']} if 'enum' in value else {})}
                       for key, value in schema['properties'].items() if key not in BLOCKED and key != 'scheduleKind'},
            'commandFields': {key: {'type': value.get('type', 'object')} for key, value in schema['properties'].items()},
        }
    return ('// Generated by scripts/generate_schedule_ui.py from Product schemas.\n'
            'export interface ScheduleField { type: string; enum?: readonly string[] }\n'
            'export interface ScheduleInputs { required: readonly string[]; fields: Record<string, ScheduleField>; commandFields: Record<string, ScheduleField> }\n'
            'export const scheduleInputs: Record<string, ScheduleInputs> = ' + json.dumps(configs, ensure_ascii=False, indent=2) + ';\n')


def render_source_import():
    package = SOURCE_IMPORT['schemas']['ScheduleSourceImportPackage']['properties']
    normalized = SOURCE_IMPORT['source_identity']['normalized_document']
    config = {
        'contractVersion': SOURCE_IMPORT['version'],
        'inputMode': package['inputMode']['enum'][0],
        'parserVersion': package['parserVersion']['enum'][0],
        'normalizedFormat': normalized['format'],
        'documentProperties': normalized['properties'],
        'scheduleExcludes': normalized['schedule_excludes'],
        'activityProperties': normalized['activities_include'],
        'activityExcludes': normalized['activities_exclude'],
        'missingLogicArraysMeanEmpty': normalized['missing_logic_arrays_mean_empty'],
        'kinds': SOURCE_IMPORT['kinds'],
    }
    return ('// Generated by scripts/generate_schedule_ui.py from Product source-import contract.\n'
            'export const scheduleSourceImport = ' + json.dumps(config, ensure_ascii=False, indent=2) + ' as const;\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    targets = {
        ROOT / 'apps/web/src/data/schedule-fields.generated.ts': render(),
        ROOT / 'apps/web/src/data/schedule-source-import.generated.ts': render_source_import(),
    }
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, output in targets.items()
                 if not path.exists() or path.read_text() != output]
        if stale:
            raise SystemExit('Schedule UI generated data are out of date: ' + ', '.join(stale))
        print('Schedule UI generated data match Product contracts')
    else:
        for path, output in targets.items():
            path.write_text(output)
