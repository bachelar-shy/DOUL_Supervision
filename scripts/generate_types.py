"""Deterministic TypeScript declarations from authoritative domain JSON Schema."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]


def ts(schema):
    if '$ref' in schema:return schema['$ref'].split('/')[-1]
    if 'const' in schema:return json.dumps(schema['const'],ensure_ascii=False)
    if 'enum' in schema:return ' | '.join(json.dumps(v,ensure_ascii=False) for v in schema['enum'])
    t=schema.get('type')
    if isinstance(t,list):return ' | '.join(ts({**schema,'type':v}) for v in t)
    if t in ['integer','number']:return 'number'
    if t=='string':return 'string'
    if t=='boolean':return 'boolean'
    if t=='null':return 'null'
    if t=='array':return 'Array<'+ts(schema.get('items',{}))+'>'
    if t=='object':
        props=schema.get('properties',{});required=schema.get('required',[])
        fields=[json.dumps(k)+('' if k in required else '?')+': '+ts(v)+';' for k,v in props.items()]
        if schema.get('additionalProperties',True):fields.append('[key: string]: unknown;')
        return '{ '+ ' '.join(fields)+' }'
    return 'unknown'


def generate():
    schemas=json.loads((ROOT/'app/schema/domain_schemas_v2.json').read_text())['components']['schemas']
    schemas.update(json.loads((ROOT/'app/schema/schedule_source_import_contract_v1.json').read_text())['schemas'])
    machines=json.loads((ROOT/'app/schema/state_machines_v1.json').read_text())['machines']
    catalog=json.loads((ROOT/'app/schema/register_catalog.json').read_text())
    parts=['// Generated by scripts/generate_types.py. JSON Schema remains authoritative.', '// Conditional JSON Schema rules are enforced at runtime by validation, not TypeScript.', 'export type UUID = string;']
    for name,schema in schemas.items():parts.append('export type '+name+' = '+ts(schema)+';')
    parts.append('export type RegisterId = '+ ' | '.join(json.dumps(f'{i:02}') for i in range(1,30))+';')
    parts.append('export type ViewId = '+ ' | '.join(json.dumps(v['id']) for v in catalog['views'])+';')
    parts.append('export type ActorGroup = RoleAssignment["actorGroup"];')
    parts.append('export type DomainObjectKind = DomainRef["objectType"];')
    parts.append('export type DomainCommand = '+' | '.join(json.dumps(m+':'+c) for m,v in machines.items() for c in dict.fromkeys(t['command'] for t in v['transitions']))+';')
    parts.append('export type RegisterProjection<T> = Readonly<{ sourceDomainRefs: ReadonlyArray<DomainRef>; data: Readonly<T> }>;')
    return '\n\n'.join(parts)+'\n'


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=ROOT/'app/types/supervision.ts';output=generate()
    if args.check:
        if path.read_text()!=output:raise SystemExit('Types are stale: run python scripts/generate_types.py')
        print('TypeScript declarations are current')
    else:path.write_text(output);print('Generated TypeScript declarations')
if __name__=='__main__':main()
